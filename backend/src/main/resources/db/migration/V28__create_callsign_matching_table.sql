-- P2-4 (часть 1 — схема): таблица соответствия позывных flight id (FI), паритет SITA
-- AIRCOM Sequencer "callsign matching table" (CLAUDE.md: «callsign matching table (ICAO code,
-- даты, дни недели, dep/arr airport)»). Разбор позывного (callsign -> carrier code + flight
-- number) и сам алгоритм матчинга — часть 2 (integration-dev). Эта миграция — ТОЛЬКО схема.
--
-- Назначение: позывной борта в эфире (например рейс "AFL1234") разбирается на ICAO-код
-- перевозчика ("AFL") + номер рейса ("1234"); по этой паре + дате/дню недели/аэропортам
-- вылета-прилёта подбирается правило, результат которого — flight_id (FI). FI используется
-- движком наравне с tail number (AN) для привязки последовательности к рейсу (CLAUDE.md:
-- «Привязка к борту: tail number (AN) ИЛИ flight id (FI)+flight data»).
--
-- Аддитивная миграция: новая таблица, не затрагивает V1-V27 и существующие демо-сценарии
-- (V9/V11/V13/V14/V17/V18/V19) — безопасна на чистой и заполненной БД.

CREATE TABLE callsign_matching (
    id                  BIGSERIAL       PRIMARY KEY,

    -- ICAO-код перевозчика, разобранный из позывного (3 буквы, напр. AFL/SVR/BAW).
    -- NOT NULL — без перевозчика правило бессмысленно (это всегда ICAO-часть позывного).
    icao_carrier_code   VARCHAR(10)     NOT NULL,

    -- Номер рейса (числовая/буквенно-числовая часть позывного после ICAO-кода, напр. "1234").
    -- NULL = правило действует для ЛЮБОГО номера рейса этого перевозчика (общее правило,
    -- низкая specificity); конкретный номер делает правило более специфичным.
    flight_number       VARCHAR(20),

    -- Результат сопоставления — flight id (FI), который движок использует для привязки
    -- последовательности к рейсу (CLAUDE.md: "tail number (AN) ИЛИ flight id (FI)+flight data").
    flight_id           VARCHAR(50)     NOT NULL,

    -- Период действия правила. Оба NULL = бессрочное правило (действует всегда).
    -- valid_from включительно, valid_to включительно (типичная семантика SITA-расписаний).
    valid_from          DATE,
    valid_to            DATE,

    -- Дни недели действия — VARCHAR(7) битовая маска, позиция 1..7 = понедельник..воскресенье
    -- ('1' — действует в этот день, '0' — не действует), напр. '1111100' = будни (Пн-Пт).
    -- NULL = действует во все дни недели (без ограничения).
    --
    -- Обоснование представления: ISO-8601 нумерация дней (Пн=1..Вс=7, как
    -- java.time.DayOfWeek.getValue()) человекочитаема при разборе строки напрямую по индексу
    -- (day_of_week.getValue() - 1), не требует доп. таблицы/enum-массива и тривиально
    -- проверяется в SQL через SUBSTRING(days_of_week, n, 1) = '1' — то же текстовое
    -- представление, что уже используется в проекте для статусных полей (VARCHAR), без
    -- введения нового типа данных (battlefield-минимум, без "на будущее").
    days_of_week        VARCHAR(7)      CHECK (days_of_week IS NULL OR days_of_week ~ '^[01]{7}$'),

    -- Аэропорты вылета/прилёта (ICAO или IATA код — формат не валидируется на уровне схемы,
    -- разбор/нормализация — часть 2). NULL = любой аэропорт (правило не ограничено по аэропорту).
    departure_airport   VARCHAR(10),
    arrival_airport     VARCHAR(10),

    -- Приоритет правила при множественном совпадении кандидатов: ЧЕМ ВЫШЕ значение, ТЕМ
    -- БОЛЕЕ КОНКРЕТНО правило и тем больший приоритет оно имеет (часть 2 сортирует кандидатов
    -- по specificity DESC и берёт первый). Значение не вычисляется автоматически в БД —
    -- задаётся явно при создании правила (как приоритет в SITA callsign matching table),
    -- по умолчанию 0 (наименее специфичное — общее правило "перевозчик -> FI" без
    -- доп. условий). Типичная схема для часть 2: общее правило перевозчика = 0, + конкретный
    -- flight_number = выше, + период действия = выше, + конкретные аэропорты = ещё выше —
    -- итоговое число специфичности часть 2 определяет сама при создании правила.
    specificity         INTEGER         NOT NULL DEFAULT 0,

    -- Признак активности правила — неактивные правила не участвуют в матчинге, но сохраняются
    -- (история/аудит), по аналогии с active на sequences (V2).
    active              BOOLEAN         NOT NULL DEFAULT true,

    created_at          TIMESTAMP       NOT NULL DEFAULT now()
);

-- Горячий путь матчинга (часть 2): "по ICAO-коду перевозчика найти активные правила-кандидаты".
-- Это первый и самый избирательный фильтр запроса — основной индекс матчинга.
CREATE INDEX idx_callsign_matching_carrier ON callsign_matching (icao_carrier_code) WHERE active;

-- Второй фильтр горячего пути: сужение кандидатов по периоду действия (valid_from/valid_to)
-- сразу после выборки по перевозчику — составной индекс покрывает диапазонную проверку
-- "valid_from <= :date AND (valid_to IS NULL OR valid_to >= :date)" без полного скана.
CREATE INDEX idx_callsign_matching_carrier_period
    ON callsign_matching (icao_carrier_code, valid_from, valid_to) WHERE active;

-- Третий ожидаемый запрос: подбор кандидатов по паре аэропортов вылета/прилёта (часть критерия
-- матчинга наравне с перевозчиком) — отдельный индекс, так как не всегда участвует первым
-- (есть правила без привязки к аэропорту, departure_airport/arrival_airport NULL).
CREATE INDEX idx_callsign_matching_airports
    ON callsign_matching (departure_airport, arrival_airport) WHERE active;

-- Демо-данные (канонический сценарий VP-BQR / SU1234, см. V13/V17): позывной "AFL1234"
-- (ICAO-код перевозчика "AFL" + номер рейса "1234") сопоставляется с flight id "SU1234" —
-- общее правило перевозчика (specificity 0) и более специфичное правило с конкретным номером
-- рейса и будними днями действия (specificity 10), демонстрирующее приоритет specificity при
-- множественном совпадении. Не затрагивает существующие демо-последовательности/тесты V9/V11/
-- V13/V14 (это новая независимая таблица).
INSERT INTO callsign_matching
    (icao_carrier_code, flight_number, flight_id, valid_from, valid_to, days_of_week,
     departure_airport, arrival_airport, specificity, active)
VALUES
    ('AFL', NULL, 'SU1234', NULL, NULL, NULL, NULL, NULL, 0, true),
    ('AFL', '1234', 'SU1234', NULL, NULL, '1111100', 'UUEE', 'ULLI', 10, true);

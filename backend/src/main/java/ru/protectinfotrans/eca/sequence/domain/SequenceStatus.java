package ru.protectinfotrans.eca.sequence.domain;

/**
 * Статусы жизненного цикла последовательности.
 *
 * См. диплом: раздел 1.3.5 (UC-04 Активировать последовательность)
 */
public enum SequenceStatus {

    /** Черновик — последовательность в процессе редактирования */
    DRAFT,

    /** Активна — последовательность обрабатывает события */
    ACTIVE,

    /** Неактивна — последовательность деактивирована */
    INACTIVE
}

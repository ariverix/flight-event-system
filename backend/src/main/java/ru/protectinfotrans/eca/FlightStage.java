package ru.protectinfotrans.eca;

/**
 * Стадии полёта OOOI.
 * Init — начальная стадия до начала движения.
 * Out/Off/On/In — четыре ключевых момента полёта, фиксируемых автоматически.
 *
 * См. диплом: раздел 1.1.4
 */
public enum FlightStage {

    /** Начальная стадия до начала движения */
    INIT,

    /** Out — выкатка от гейта */
    OUT,

    /** Off — взлёт */
    OFF,

    /** On — посадка */
    ON,

    /** In — прибытие на гейт */
    IN
}

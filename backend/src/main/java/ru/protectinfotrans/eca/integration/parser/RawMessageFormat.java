package ru.protectinfotrans.eca.integration.parser;

/**
 * Формат сырого сообщения «борт-земля», принятого на raw-эндпоинте
 * ({@code POST /api/v1/messages/incoming/raw}).
 *
 * <p>Указывается явно вызывающей стороной (ACARS-шлюз/симулятор/реальная наземная
 * станция знает, по какому каналу/формату пришло сообщение) — без авто-детекта.
 * Авто-детект по структуре текста был рассмотрен и отклонён: форматы Type B и AFTN
 * могут начинаться визуально похожими блоками заголовка, ARINC 618/620 не имеют
 * единой сигнатуры начала сообщения — угадывание формата на проде означало бы
 * молчаливый риск неверной интерпретации полезной нагрузки (борт/рейс перепутаны
 * между парсерами), что для привязки последовательностей (AN/FI) недопустимо.
 * Явный формат — отказоустойчивее: ошибка диспетчеризации форматом видна сразу
 * как явный 400, а не как тихо неверно распарсенный борт.
 */
public enum RawMessageFormat {
    /** ARINC 618 — air-ground (downlink/uplink), текстовые ACARS-сообщения. */
    ARINC_618,
    /** ARINC 620 — ground-ground, обмен между наземными системами. */
    ARINC_620,
    /** Type B — классическая авиационная телеграмма (адресный блок + текст). */
    TYPE_B,
    /** AFTN — Aeronautical Fixed Telecommunication Network телеграмма. */
    AFTN
}
